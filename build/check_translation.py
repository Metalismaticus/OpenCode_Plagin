ALLOW_RE = re.compile("|".join(re.escape(a) for a in sorted(ALLOW, key=len, reverse=True)))
CYR_RE = re.compile(r"[А-Яа-яЁё]")

FLAG_FRONTMATTER_DESC = True  # description остаётся русским — не флагаем

suspicious = 0
for path in FILES:
    rel = os.path.relpath(path, ROOT)
    in_fence = False
    in_front = False
    front_done = False
    flagged = []
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            if line.strip().startswith("```"):
                in_fence = not in_fence
                continue
            if not front_done:
                if line.startswith("---") and (n <= 2 or in_front):
                    if in_front:
                        front_done = True
                    in_front = not in_front
                    continue
                if in_front and FLAG_FRONTMATTER_DESC:
                    continue  # frontmatter — русский по правилам
            if in_fence:
                continue  # код-блоки форматов — русские дословно
            if not CYR_RE.search(line):
                continue
            # вся кириллица строки должна покрываться разрешённым словарём
            stripped = ALLOW_RE.sub("", line)
            if CYR_RE.search(stripped):
                flagged.append((n, line.rstrip()))
    if flagged:
        print(f"=== {rel}: {len(flagged)} подозрительных строк")
        for n, line in flagged[:12]:
            print(f"  :{n} {line.strip()[:120]}")
        if len(flagged) > 12:
            print(f"  … ещё {len(flagged) - 12}")
        suspicious += len(flagged)

print()
